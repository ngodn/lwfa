#!/usr/bin/env node
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
const root = fileURLToPath(new URL('../', import.meta.url))
const require = createRequire(path.join(root, 'packages/shell/package.json'))
const { build } = await import(pathToFileURL(require.resolve('vite')).href)
const result = await build({
  configFile: false, root, logLevel: 'warn',
  build: {
    write: false, target: 'safari17', minify: false,
    lib: { entry: path.join(root, 'clients/ios/LayoutBridge.ts'), name: 'LWFALayout', formats: ['iife'] },
  },
})
const outputs = Array.isArray(result) ? result : [result]
const chunks = outputs.flatMap(output => output.output).filter(item => item.type === 'chunk')
if (chunks.length !== 1) throw new Error('Expected one self-contained layout bundle')
const destination = path.join(root, 'clients/ios/NativeApp/Resources/layout.js')
await mkdir(path.dirname(destination), { recursive: true })
await writeFile(destination, '// Generated by scripts/build-ios-layout.mjs. Do not edit.\n' + chunks[0].code)
console.log('Built native layout from canonical shell policy.')
