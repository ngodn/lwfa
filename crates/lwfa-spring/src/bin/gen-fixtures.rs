//! Emits the Rust side of the spring parity fixtures.
//!
//! Reads `fixtures/cases.tsv` (shared with the TypeScript implementation) and
//! writes sampled curves to `fixtures/rust.samples.tsv` and settle estimates to
//! `fixtures/rust.settle.tsv`. `packages/spring/test/parity.test.ts` then checks
//! its own output against these, and against upstream `motion-dom`.
//!
//! Floats are written with `{:?}`, which is Rust's shortest round-tripping
//! representation, so the comparison is limited by the maths and not by the
//! serialisation.
//!
//! Run from the repo root: `cargo run -p lwfa-spring --bin gen-fixtures`

use lwfa_spring::{Spring, SpringOptions};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// Matches the sampling in `Spring::settle_time_ms` calls on the TS side.
const SETTLE_MAX_MS: f64 = 30_000.0;
const SETTLE_STEP_MS: f64 = 4.0;

struct Case {
    name: String,
    options: SpringOptions,
    from: f64,
    to: f64,
    t_max_ms: f64,
    step_ms: f64,
}

fn repo_root() -> PathBuf {
    // CARGO_MANIFEST_DIR is crates/lwfa-spring, so go up two.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crate should live two levels below the repo root")
        .to_path_buf()
}

fn parse_cases(src: &str) -> Result<Vec<Case>, String> {
    let mut cases = Vec::new();

    for (lineno, line) in src.lines().enumerate() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') || line.starts_with("name\t") {
            continue;
        }

        let f: Vec<&str> = line.split('\t').collect();
        if f.len() != 9 {
            return Err(format!(
                "cases.tsv line {}: expected 9 tab-separated columns, got {}",
                lineno + 1,
                f.len()
            ));
        }

        let num = |i: usize| -> Result<f64, String> {
            f[i].trim()
                .parse::<f64>()
                .map_err(|e| format!("cases.tsv line {}: column {}: {e}", lineno + 1, i + 1))
        };

        cases.push(Case {
            name: f[0].to_string(),
            options: SpringOptions {
                stiffness: num(1)?,
                damping: num(2)?,
                mass: num(3)?,
                velocity: num(4)?,
                rest_speed: None,
                rest_delta: None,
            },
            from: num(5)?,
            to: num(6)?,
            t_max_ms: num(7)?,
            step_ms: num(8)?,
        });
    }

    if cases.is_empty() {
        return Err("cases.tsv contained no cases".to_string());
    }
    Ok(cases)
}

fn main() -> ExitCode {
    let root = repo_root();
    let cases_path = root.join("fixtures/cases.tsv");

    let src = match fs::read_to_string(&cases_path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("failed to read {}: {e}", cases_path.display());
            return ExitCode::FAILURE;
        }
    };

    let cases = match parse_cases(&src) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };

    let mut samples = String::from(
        "# Generated by `cargo run -p lwfa-spring --bin gen-fixtures`. Do not edit.\nname\tt_ms\tvalue\tvelocity\tdone\n",
    );
    let mut settle = String::from(
        "# Generated by `cargo run -p lwfa-spring --bin gen-fixtures`. Do not edit.\nname\tsettle_ms\n",
    );
    let mut rows = 0usize;

    for case in &cases {
        let spring = Spring::new(case.options, case.from, case.to);

        // Step count is derived rather than accumulated so the TS side lands on
        // identical sample times instead of drifting by float addition.
        let steps = (case.t_max_ms / case.step_ms).floor() as u64;
        for i in 0..=steps {
            let t = i as f64 * case.step_ms;
            let state = spring.state_at(t);
            let velocity = spring.velocity_at(t);

            if !state.value.is_finite() || !velocity.is_finite() {
                eprintln!(
                    "case {} produced a non-finite sample at t={t}ms (value={}, velocity={velocity})",
                    case.name, state.value
                );
                return ExitCode::FAILURE;
            }

            let _ = writeln!(
                samples,
                "{}\t{:?}\t{:?}\t{:?}\t{}",
                case.name,
                t,
                state.value,
                velocity,
                u8::from(state.done)
            );
            rows += 1;
        }

        let _ = writeln!(
            settle,
            "{}\t{:?}",
            case.name,
            spring.settle_time_ms(SETTLE_MAX_MS, SETTLE_STEP_MS)
        );
    }

    let samples_path = root.join("fixtures/rust.samples.tsv");
    let settle_path = root.join("fixtures/rust.settle.tsv");

    if let Err(e) = fs::write(&samples_path, samples) {
        eprintln!("failed to write {}: {e}", samples_path.display());
        return ExitCode::FAILURE;
    }
    if let Err(e) = fs::write(&settle_path, settle) {
        eprintln!("failed to write {}: {e}", settle_path.display());
        return ExitCode::FAILURE;
    }

    println!(
        "wrote {rows} samples across {} cases to {} and {}",
        cases.len(),
        samples_path.display(),
        settle_path.display()
    );
    ExitCode::SUCCESS
}
