/**
 * The shell protocol, TypeScript side.
 *
 * Mirrors `crates/lwfa-proto`. Read that crate's module docs for the design;
 * this file is the wire mapping and a strict runtime decoder.
 *
 * # Why a runtime decoder and not just types
 *
 * TypeScript types vanish at runtime, so `JSON.parse(...) as ToShell` asserts
 * nothing. If the engine renamed `appId` and this side did not, the field would
 * quietly read `undefined` and windows would lose their names with no error
 * anywhere. The decoders below check the shape for real, and
 * `test/parity.test.ts` runs them against fixtures generated by the Rust
 * implementation.
 *
 * Decoding is strict about unknown fields, matching `deny_unknown_fields` on
 * the Rust side. Protocol evolution goes through {@link PROTOCOL_VERSION}, not
 * through silently tolerated extra keys.
 */

/** Bumped on any breaking change. Must equal the Rust `PROTOCOL_VERSION`. */
export const PROTOCOL_VERSION = 0

/** Engine-assigned window handle. A bare number on the wire. */
export type WindowId = number

export interface Output {
  width: number
  height: number
  scale: number
}

export interface Rect {
  x: number
  y: number
  width: number
  height: number
}

export interface WindowInfo {
  id: WindowId
  appId: string | null
  title: string | null
}

export interface SpringSpec {
  stiffness: number
  damping: number
  mass: number
}

export interface Animation {
  spring: SpringSpec
}

export interface WindowLayout {
  id: WindowId
  rect: Rect
  z: number
}

/**
 * A pointer button, Linux evdev numbering (`BTN_LEFT` = 0x110).
 * Not the browser's 0/1/2, which is a different numbering entirely.
 */
export type ButtonCode = number

/**
 * A key, Linux evdev numbering (`KEY_A` = 30).
 *
 * Derived from `KeyboardEvent.code` (the physical key), never from
 * `KeyboardEvent.key` (the character), or the layout would be applied twice.
 * See `packages/shell/src/input.ts`.
 */
export type KeyCode = number

/** Keyboard modifier state at the time of a key press. */
export interface Modifiers {
  alt: boolean
  ctrl: boolean
  shift: boolean
  /** The Super/Windows/Command key. */
  logo: boolean
}

export type ToShell =
  | {
      type: "hello"
      protocolVersion: number
      output: Output
      windows: WindowInfo[]
      focused: WindowId | null
      permissions: Permissions
      /** Which account this is. "owner" for AUTH_PASS. */
      account: string
    }
  | { type: "outputChanged"; output: Output }
  | { type: "windowOpened"; window: WindowInfo }
  | { type: "windowChanged"; window: WindowInfo }
  | { type: "windowClosed"; id: WindowId }
  | { type: "focusChanged"; id: WindowId | null }
  /**
   * A modified key the engine did not claim for itself.
   *
   * "Focus the column to the left" is layout policy, so it belongs to the
   * shell. `key` is an xkb keysym name such as `"h"`, `"Left"` or `"Return"`.
   */
  | { type: "keyBinding"; key: string; modifiers: Modifiers }
  /**
   * Installed applications, in reply to `listApps`.
   *
   * On request rather than in `hello`, because scanning the desktop entries
   * touches the filesystem and most sessions never open the launcher.
   */
  | { type: "apps"; apps: AppEntry[] }
  /** The accounts on this machine. Never contains a password or a hash. */
  | { type: "accounts"; accounts: AccountInfo[] }
  /**
   * A request with a visible result did not happen, and why.
   *
   * Distinct from a dropped message: this exists so the UI can say "that name
   * is taken" rather than leaving a dialog waiting for a reply.
   */
  | { type: "error"; request: string; message: string }

/**
 * What a connected session is allowed to do.
 *
 * Advisory here: the shell uses it to grey out what it cannot use. The engine
 * enforces it. A permission checked only in the browser is not a permission,
 * it is a suggestion.
 */
export interface Permissions {
  mode: SessionMode
  /** Desktop entry ids this session may launch. `null` means all of them. */
  allowedApps: string[] | null
}

export type SessionMode = "view" | "interact"

/** One account, as the Access panel sees it. */
export interface AccountInfo {
  id: number
  name: string
  permissions: Permissions
}

/** One launchable application, from a freedesktop `.desktop` entry. */
export interface AppEntry {
  /** The desktop file's basename without its extension. */
  id: string
  name: string
  description: string | null
  /** `Exec=`, with the freedesktop field codes (%f, %U, ...) removed. */
  exec: string
  /** An icon *name*, not a path. The shell has no icon theme; this is a hint. */
  icon: string | null
  categories: string[]
  terminal: boolean
}

export type ToEngine =
  | { type: "setLayout"; windows: WindowLayout[]; animate: Animation | null }
  | { type: "focusWindow"; id: WindowId }
  | { type: "closeWindow"; id: WindowId }
  | { type: "spawn"; command: string }
  /** Ask for the installed applications. Answered with `apps`. */
  | { type: "listApps" }
  /** Account administration. All four require the owner. */
  | { type: "listAccounts" }
  | { type: "createAccount"; name: string; password: string; permissions: Permissions }
  | { type: "updateAccount"; id: number; permissions: Permissions; password: string | null }
  | { type: "deleteAccount"; id: number }
  /**
   * Which windows the shell wants pixels for. Total: anything not listed stops
   * streaming. A shell compositing natively asks for none.
   */
  /**
   * Which windows to stream, and whether this client can decode H.264.
   *
   * `h264: false` is not hypothetical: WebCodecs `VideoDecoder` is only
   * exposed in a secure context, so a browser reached over plain HTTP on a LAN
   * address has no H.264 decoder while the same browser on localhost does.
   */
  | { type: "setStreams"; windows: WindowId[]; h264: boolean }
  /**
   * Pointer moved within a window. Coordinates are window-relative logical
   * pixels, because during an animation the engine's actual window position
   * differs from the shell's target and output-relative coordinates would land
   * clicks where the window is heading rather than where it is.
   */
  | { type: "pointerMotion"; window: WindowId; x: number; y: number }
  | { type: "pointerButton"; button: ButtonCode; pressed: boolean }
  | { type: "pointerAxis"; horizontal: number; vertical: number }
  | { type: "pointerLeave" }
  | { type: "key"; key: KeyCode; pressed: boolean }
  /** Touch is first-class, not synthesised into pointer events. */
  | { type: "touchDown"; window: WindowId; id: number; x: number; y: number }
  | { type: "touchMotion"; window: WindowId; id: number; x: number; y: number }
  | { type: "touchUp"; id: number }

/** Motion's defaults, matching `SpringSpec::default` on the Rust side. */
export const DEFAULT_SPRING: SpringSpec = { stiffness: 100, damping: 10, mass: 1 }

export class ProtocolError extends Error {
  constructor(message: string) {
    super(message)
    this.name = "ProtocolError"
  }
}

// ---------------------------------------------------------------------------
// Strict field readers
//
// Hand-rolled rather than pulled from a validation library: the shell ships to
// a phone over a mobile connection, this is the only place that needs it, and
// being explicit about rejecting unknown keys is the entire point.
// ---------------------------------------------------------------------------

type Obj = Record<string, unknown>

function asObject(value: unknown, at: string): Obj {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new ProtocolError(`${at}: expected an object, got ${describe(value)}`)
  }
  return value as Obj
}

function describe(value: unknown): string {
  if (value === null) return "null"
  if (Array.isArray(value)) return "an array"
  return typeof value
}

/** Reject any key the schema does not name, mirroring `deny_unknown_fields`. */
function noExtraKeys(obj: Obj, allowed: readonly string[], at: string): void {
  for (const key of Object.keys(obj)) {
    if (!allowed.includes(key)) {
      throw new ProtocolError(
        `${at}: unknown field ${JSON.stringify(key)}, expected one of ${allowed.join(", ")}`,
      )
    }
  }
}

function num(obj: Obj, key: string, at: string): number {
  const v = obj[key]
  if (typeof v !== "number" || !Number.isFinite(v)) {
    throw new ProtocolError(`${at}.${key}: expected a finite number, got ${describe(v)}`)
  }
  return v
}

function int(obj: Obj, key: string, at: string): number {
  const v = num(obj, key, at)
  if (!Number.isInteger(v)) {
    throw new ProtocolError(`${at}.${key}: expected an integer, got ${v}`)
  }
  return v
}

function str(obj: Obj, key: string, at: string): string {
  const v = obj[key]
  if (typeof v !== "string") {
    throw new ProtocolError(`${at}.${key}: expected a string, got ${describe(v)}`)
  }
  return v
}

/**
 * Rust `Option<T>` serialises to `null`, never to an absent key, so a missing
 * key is a real error rather than an implicit None.
 */
function nullableStr(obj: Obj, key: string, at: string): string | null {
  const v = obj[key]
  if (v === null) return null
  if (typeof v !== "string") {
    throw new ProtocolError(`${at}.${key}: expected a string or null, got ${describe(v)}`)
  }
  return v
}

function nullableId(obj: Obj, key: string, at: string): WindowId | null {
  const v = obj[key]
  if (v === null) return null
  return int(obj, key, at)
}

function array(obj: Obj, key: string, at: string): unknown[] {
  const v = obj[key]
  if (!Array.isArray(v)) {
    throw new ProtocolError(`${at}.${key}: expected an array, got ${describe(v)}`)
  }
  return v
}

function tag(obj: Obj, at: string): string {
  const v = obj["type"]
  if (typeof v !== "string") {
    throw new ProtocolError(`${at}: missing discriminant "type"`)
  }
  return v
}

// ---------------------------------------------------------------------------
// Component decoders
// ---------------------------------------------------------------------------

function decodeOutput(value: unknown, at: string): Output {
  const o = asObject(value, at)
  noExtraKeys(o, ["width", "height", "scale"], at)
  return { width: int(o, "width", at), height: int(o, "height", at), scale: num(o, "scale", at) }
}

function decodeRect(value: unknown, at: string): Rect {
  const o = asObject(value, at)
  noExtraKeys(o, ["x", "y", "width", "height"], at)
  return {
    x: num(o, "x", at),
    y: num(o, "y", at),
    width: num(o, "width", at),
    height: num(o, "height", at),
  }
}

function decodeWindowInfo(value: unknown, at: string): WindowInfo {
  const o = asObject(value, at)
  noExtraKeys(o, ["id", "appId", "title"], at)
  return {
    id: int(o, "id", at),
    appId: nullableStr(o, "appId", at),
    title: nullableStr(o, "title", at),
  }
}

function decodeSpring(value: unknown, at: string): SpringSpec {
  const o = asObject(value, at)
  noExtraKeys(o, ["stiffness", "damping", "mass"], at)
  return {
    stiffness: num(o, "stiffness", at),
    damping: num(o, "damping", at),
    mass: num(o, "mass", at),
  }
}

function decodeAnimation(value: unknown, at: string): Animation | null {
  if (value === null) return null
  const o = asObject(value, at)
  noExtraKeys(o, ["spring"], at)
  return { spring: decodeSpring(o["spring"], `${at}.spring`) }
}

function bool(obj: Obj, key: string, at: string): boolean {
  const v = obj[key]
  if (typeof v !== "boolean") {
    throw new ProtocolError(`${at}.${key}: expected a boolean, got ${describe(v)}`)
  }
  return v
}

function decodeModifiers(value: unknown, at: string): Modifiers {
  const o = asObject(value, at)
  noExtraKeys(o, ["alt", "ctrl", "shift", "logo"], at)
  return {
    alt: bool(o, "alt", at),
    ctrl: bool(o, "ctrl", at),
    shift: bool(o, "shift", at),
    logo: bool(o, "logo", at),
  }
}

function decodeWindowLayout(value: unknown, at: string): WindowLayout {
  const o = asObject(value, at)
  noExtraKeys(o, ["id", "rect", "z"], at)
  return { id: int(o, "id", at), rect: decodeRect(o["rect"], `${at}.rect`), z: int(o, "z", at) }
}

