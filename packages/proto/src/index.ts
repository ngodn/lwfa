/** Parse a message from the engine. Throws {@link ProtocolError} on any mismatch. */
export function decodeToShell(text: string): ToShell {
  const at = "ToShell"
  const o = asObject(parse(text, at), at)
  const t = tag(o, at)

  switch (t) {
    case "hello": {
      const where = `${at}.hello`
      noExtraKeys(
        o,
        ["type", "protocolVersion", "output", "windows", "focused", "permissions", "account"],
        where,
      )
      return {
        type: "hello",
        protocolVersion: int(o, "protocolVersion", where),
        output: decodeOutput(o["output"], `${where}.output`),
        windows: array(o, "windows", where).map((w, i) =>
          decodeWindowInfo(w, `${where}.windows[${i}]`),
        ),
        focused: nullableId(o, "focused", where),
        permissions: decodePermissions(o["permissions"], `${where}.permissions`),
        account: str(o, "account", where),
      }
    }
    case "outputChanged": {
      const where = `${at}.outputChanged`
      noExtraKeys(o, ["type", "output"], where)
      return { type: "outputChanged", output: decodeOutput(o["output"], `${where}.output`) }
    }
    case "windowOpened":
    case "windowChanged": {
      const where = `${at}.${t}`
      noExtraKeys(o, ["type", "window"], where)
      return { type: t, window: decodeWindowInfo(o["window"], `${where}.window`) }
    }
    case "windowClosed": {
      const where = `${at}.windowClosed`
      noExtraKeys(o, ["type", "id"], where)
      return { type: "windowClosed", id: int(o, "id", where) }
    }
    case "focusChanged": {
      const where = `${at}.focusChanged`
      noExtraKeys(o, ["type", "id"], where)
      return { type: "focusChanged", id: nullableId(o, "id", where) }
    }
    case "keyBinding": {
      const where = `${at}.keyBinding`
      noExtraKeys(o, ["type", "key", "modifiers"], where)
      return {
        type: "keyBinding",
        key: str(o, "key", where),
        modifiers: decodeModifiers(o["modifiers"], `${where}.modifiers`),
      }
    }
    case "accounts": {
      const where = `${at}.accounts`
      noExtraKeys(o, ["type", "accounts"], where)
      const list = o["accounts"]
      if (!Array.isArray(list)) throw new ProtocolError(`${where}.accounts: expected an array`)
      return {
        type: "accounts",
        accounts: list.map((a, i) => decodeAccount(a, `${where}.accounts[${i}]`)),
      }
    }
    case "error": {
      const where = `${at}.error`
      noExtraKeys(o, ["type", "request", "message"], where)
      return { type: "error", request: str(o, "request", where), message: str(o, "message", where) }
    }
    case "apps": {
      const where = `${at}.apps`
      noExtraKeys(o, ["type", "apps"], where)
      const list = o["apps"]
      if (!Array.isArray(list)) throw new ProtocolError(`${where}.apps: expected an array`)
      return { type: "apps", apps: list.map((app, i) => decodeApp(app, `${where}.apps[${i}]`)) }
    }
    default:
      throw new ProtocolError(`${at}: unknown message type ${JSON.stringify(t)}`)
  }
}

function decodeAccount(value: unknown, at: string): AccountInfo {
  const o = asObject(value, at)
  noExtraKeys(o, ["id", "name", "permissions"], at)
  return {
    id: int(o, "id", at),
    name: str(o, "name", at),
    permissions: decodePermissions(o["permissions"], `${at}.permissions`),
  }
}

function decodePermissions(value: unknown, at: string): Permissions {
  const o = asObject(value, at)
  noExtraKeys(o, ["mode", "allowedApps"], at)
  const mode = str(o, "mode", at)
  if (mode !== "view" && mode !== "interact") {
    throw new ProtocolError(`${at}.mode: expected "view" or "interact", got ${mode}`)
  }
  const allowed = o["allowedApps"]
  if (allowed !== null && !Array.isArray(allowed)) {
    throw new ProtocolError(`${at}.allowedApps: expected an array or null`)
  }
  return {
    mode,
    allowedApps:
      allowed === null
        ? null
        : allowed.map((a, i) => {
            if (typeof a !== "string") {
              throw new ProtocolError(`${at}.allowedApps[${i}]: expected a string`)
            }
            return a
          }),
  }
}

function decodeApp(value: unknown, at: string): AppEntry {
  const o = asObject(value, at)
  noExtraKeys(
    o,
    ["id", "name", "description", "exec", "icon", "categories", "terminal"],
    at,
  )
  const categories = o["categories"]
  if (!Array.isArray(categories)) throw new ProtocolError(`${at}.categories: expected an array`)
  return {
    id: str(o, "id", at),
    name: str(o, "name", at),
    description: nullableStr(o, "description", at),
    exec: str(o, "exec", at),
    icon: nullableStr(o, "icon", at),
    categories: categories.map((c, i) => {
      if (typeof c !== "string") throw new ProtocolError(`${at}.categories[${i}]: expected a string`)
      return c
    }),
    terminal: bool(o, "terminal", at),
  }
}

/** Parse a message from the shell. Throws {@link ProtocolError} on any mismatch. */
export function decodeToEngine(text: string): ToEngine {
  const at = "ToEngine"
  const o = asObject(parse(text, at), at)
  const t = tag(o, at)

  switch (t) {
    case "setLayout": {
      const where = `${at}.setLayout`
      noExtraKeys(o, ["type", "windows", "animate"], where)
      return {
        type: "setLayout",
        windows: array(o, "windows", where).map((w, i) =>
          decodeWindowLayout(w, `${where}.windows[${i}]`),
        ),
        animate: decodeAnimation(o["animate"], `${where}.animate`),
      }
    }
    case "focusWindow":
    case "closeWindow": {
      const where = `${at}.${t}`
      noExtraKeys(o, ["type", "id"], where)
      return { type: t, id: int(o, "id", where) }
    }
    case "spawn": {
      const where = `${at}.spawn`
      noExtraKeys(o, ["type", "command"], where)
      return { type: "spawn", command: str(o, "command", where) }
    }
    case "pointerMotion": {
      const where = `${at}.pointerMotion`
      noExtraKeys(o, ["type", "window", "x", "y"], where)
      return {
        type: "pointerMotion",
        window: int(o, "window", where),
        x: num(o, "x", where),
        y: num(o, "y", where),
      }
    }
    case "pointerButton": {
      const where = `${at}.pointerButton`
      noExtraKeys(o, ["type", "button", "pressed"], where)
      return {
        type: "pointerButton",
        button: int(o, "button", where),
        pressed: bool(o, "pressed", where),
      }
    }
    case "pointerAxis": {
      const where = `${at}.pointerAxis`
      noExtraKeys(o, ["type", "horizontal", "vertical"], where)
      return {
        type: "pointerAxis",
        horizontal: num(o, "horizontal", where),
        vertical: num(o, "vertical", where),
      }
    }
    case "pointerLeave": {
      noExtraKeys(o, ["type"], `${at}.pointerLeave`)
      return { type: "pointerLeave" }
    }
    case "key": {
      const where = `${at}.key`
      noExtraKeys(o, ["type", "key", "pressed"], where)
      return { type: "key", key: int(o, "key", where), pressed: bool(o, "pressed", where) }
    }
    case "touchDown":
    case "touchMotion": {
      const where = `${at}.${t}`
      noExtraKeys(o, ["type", "window", "id", "x", "y"], where)
      return {
        type: t,
        window: int(o, "window", where),
        id: int(o, "id", where),
        x: num(o, "x", where),
        y: num(o, "y", where),
      }
    }
    case "touchUp": {
      const where = `${at}.touchUp`
      noExtraKeys(o, ["type", "id"], where)
      return { type: "touchUp", id: int(o, "id", where) }
    }
    case "setStreams": {
      const where = `${at}.setStreams`
      noExtraKeys(o, ["type", "windows", "h264"], where)
      return {
        type: "setStreams",
        windows: array(o, "windows", where).map((w, i) => {
          if (typeof w !== "number" || !Number.isInteger(w)) {
            throw new ProtocolError(`${where}.windows[${i}]: expected an integer window id`)
          }
          return w
        }),
        h264: bool(o, "h264", where),
      }
    }
    default:
      throw new ProtocolError(`${at}: unknown message type ${JSON.stringify(t)}`)
  }
}

function parse(text: string, at: string): unknown {
  try {
    return JSON.parse(text)
  } catch (err) {
    throw new ProtocolError(`${at}: invalid JSON: ${(err as Error).message}`)
  }
}

/**
 * Serialise a message for the wire.
 *
 * Field order follows the Rust struct declaration order so a diff of two
 * captures lines up, though nothing depends on it.
 */
export function encode(message: ToShell | ToEngine): string {
  return JSON.stringify(message)
}

// ---------------------------------------------------------------------------
// Binary frame transport
//
// Window pixels do not travel as JSON. They arrive as WebSocket *binary*
// frames with the fixed header below, on the same socket: text is control,
// binary is pixels. Mirrors the Rust side in `crates/lwfa-proto`.
// ---------------------------------------------------------------------------

/** Identifies an lwfa binary frame. ASCII "LWFA". */
export const FRAME_MAGIC = [0x4c, 0x57, 0x46, 0x41] as const

/** Bumped when the header layout changes. Independent of PROTOCOL_VERSION. */
export const FRAME_VERSION = 0

/** Bytes before the payload. */
export const FRAME_HEADER_LEN = 24

/** Bit 0 of the flags byte at offset 6. */
const FLAG_KEYFRAME = 1 << 0

export const FrameFormat = {
  /** Whole-image, always self-contained. The engine's fallback when it has no
   *  hardware encoder session left (8 concurrent on the dev GPU). */
  Jpeg: 0,
  /** H.264 Annex B, SPS/PPS repeated on every keyframe. The normal path. */
  H264: 1,
} as const
export type FrameFormat = (typeof FrameFormat)[keyof typeof FrameFormat]

export interface FrameHeader {
  window: WindowId
  width: number
  height: number
  format: FrameFormat
  /**
   * A decoder can start here. Always true for JPEG; true for H.264 IDRs.
   *
   * A browser attaching mid-stream must discard frames until this is true, or
   * it feeds its decoder deltas with no reference picture.
   */
  keyframe: boolean
}

export interface DecodedFrame {
  header: FrameHeader
  payload: Uint8Array
}

/**
 * Parse a binary frame.
 *
 * Returns null rather than throwing or partially decoding, so a malformed or
 * foreign binary message is dropped instead of being drawn as garbage.
 */
export function decodeFrame(buffer: ArrayBuffer): DecodedFrame | null {
  if (buffer.byteLength < FRAME_HEADER_LEN) return null
  const bytes = new Uint8Array(buffer)

  for (let i = 0; i < FRAME_MAGIC.length; i++) {
    if (bytes[i] !== FRAME_MAGIC[i]) return null
  }
  if (bytes[4] !== FRAME_VERSION) return null
  const format = bytes[5]
  if (format !== FrameFormat.Jpeg && format !== FrameFormat.H264) return null
  const keyframe = ((bytes[6] ?? 0) & FLAG_KEYFRAME) !== 0

  const view = new DataView(buffer)
  // Window ids are u64 on the wire. Reading as BigInt and narrowing keeps this
  // honest: ids beyond 2^53 would silently collide if read as a float, and
  // that would show pixels in the wrong window.
  const id = view.getBigUint64(8, true)
  if (id > BigInt(Number.MAX_SAFE_INTEGER)) return null

  const width = view.getUint32(16, true)
  const height = view.getUint32(20, true)
  if (width === 0 || height === 0) return null

  return {
    header: { window: Number(id), width, height, format, keyframe },
    payload: bytes.subarray(FRAME_HEADER_LEN),
  }
}
